        dbTable("dbtable.trail_easy_casket", serverOnly = true) {
            column("obj", 0, VarType.OBJ)
            column("min", 1, VarType.INT)
            column("max", 2, VarType.INT)
            column("weight", 3, VarType.INT)
            column("noted", 4, VarType.BOOLEAN)
            for ((i, reward) in REWARDS.withIndex()) {
                row("dbrow.trail_easy_casket_$i") {
                    columnRSCM(0, reward.obj)
                    column(1, reward.min)
                    column(2, reward.max)
                    column(3, reward.weight)
                    column(4, reward.noted)
                }
            }
        }
